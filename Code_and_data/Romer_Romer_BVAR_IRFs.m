%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% Local estimation and plotting functions
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

function [BVAR_model, ...
        irfs_draws, ...
        policy_impact_responses, ...
        scaling_factors, ...
        irfs_draws_rescaled, ...
        irfs_mean, ...
        irfs_pointwise_std] = ...
        estimate_bvar_irfs( ...
        y, ...
        lags, ...
        options, ...
        monetary_shock_index, ...
        policy_variable_index, ...
        number_of_variables, ...
        desired_policy_impact, ...
        model_tag)
%ESTIMATE_BVAR_IRFS Estimate a BVAR and summarise posterior Cholesky IRFs.
%
% Output dimensions:
%   irfs_draws              variable x horizon x draw
%   irfs_draws_rescaled     variable x horizon x draw
%   irfs_mean               variable x horizon
%   irfs_pointwise_std      variable x horizon
%
% Each posterior draw is separately normalised so the policy variable has
% the same desired impact response in every draw. The mean and pointwise
% standard deviation are then computed across these normalised draws.

    BVAR_model = bvar_(y, lags, options);

    if ~isfield(BVAR_model, 'ir_draws')
        error(['The bvar_ output for ', model_tag, ...
            ' does not contain the field ir_draws.']);
    end

    irfs_draws = squeeze( ...
        BVAR_model.ir_draws(:, :, monetary_shock_index, :) ...
        );

    % With K > 1, the expected dimensions after squeeze are:
    % variable x horizon x draw.
    if ndims(irfs_draws) ~= 3
        error(['The extracted posterior IRFs for ', model_tag, ...
            ' are not a three-dimensional variable-by-horizon-by-draw ', ...
            'array. Check BVAR_model.ir_draws and options.K.']);
    end

    if size(irfs_draws, 1) ~= number_of_variables
        error(['The extracted posterior IRFs for ', model_tag, ...
            ' do not have the expected number of variables in their rows.']);
    end

    policy_impact_responses = squeeze( ...
        irfs_draws(policy_variable_index, 1, :) ...
        );

    policy_impact_responses = policy_impact_responses(:);

    invalid_policy_impacts = ...
        ~isfinite(policy_impact_responses) | ...
        abs(policy_impact_responses) < 1e-12;

    if any(invalid_policy_impacts)
        error(['At least one posterior IRF draw for ', model_tag, ...
            ' has an invalid or approximately zero policy impact response, ', ...
            'so draw-specific normalisation cannot be performed.']);
    end

    scaling_factors = ...
        desired_policy_impact ./ policy_impact_responses;

    irfs_draws_rescaled = ...
        irfs_draws .* reshape(scaling_factors, 1, 1, []);

    % The plotted point estimate is the mean across posterior IRF draws.
    irfs_mean = mean( ...
        irfs_draws_rescaled, ...
        3, ...
        'omitnan');

    % This matrix stores the pointwise standard deviation for every
    % variable and every horizon.
    irfs_pointwise_std = std( ...
        irfs_draws_rescaled, ...
        0, ...
        3, ...
        'omitnan');
end


function [irfs_mean_plot, ...
        irfs_pointwise_std_plot, ...
        irfs_lower_plot, ...
        irfs_upper_plot] = ...
        convert_irfs_to_plot_units( ...
        irfs_mean, ...
        irfs_pointwise_std, ...
        log_variable_indices)
%CONVERT_IRFS_TO_PLOT_UNITS Convert log responses to percentage responses.
%
% The mean and standard deviation are transformed using the same linear
% scaling. The pointwise bands are mean +/- one standard deviation.

    irfs_mean_plot = irfs_mean;
    irfs_pointwise_std_plot = irfs_pointwise_std;

    irfs_mean_plot(log_variable_indices, :) = ...
        100 .* irfs_mean(log_variable_indices, :);

    irfs_pointwise_std_plot(log_variable_indices, :) = ...
        100 .* irfs_pointwise_std(log_variable_indices, :);

    irfs_lower_plot = ...
        irfs_mean_plot - irfs_pointwise_std_plot;

    irfs_upper_plot = ...
        irfs_mean_plot + irfs_pointwise_std_plot;
end


function [figure_handle, layout_handle, axes_handles] = ...
        plot_tagged_irfs_with_bands( ...
        irfs_mean_plot, ...
        irfs_lower_plot, ...
        irfs_upper_plot, ...
        horizons, ...
        panel_indices, ...
        panel_titles, ...
        y_axis_labels, ...
        y_axis_limits, ...
        y_axis_ticks, ...
        figure_position, ...
        figure_title)
%PLOT_TAGGED_IRFS_WITH_BANDS Plot mean IRFs and one-standard-deviation bands.
%
% The solid line is the posterior mean IRF. The dashed lines are the
% pointwise posterior mean plus and minus one standard deviation.

    number_of_panels = numel(panel_indices);
    panel_letters = 'abcdefghijklmnopqrstuvwxyz';

    figure_handle = figure( ...
        'Position', figure_position, ...
        'Color', 'w');

    layout_handle = tiledlayout(number_of_panels, 1);
    layout_handle.TileSpacing = 'compact';
    layout_handle.Padding = 'compact';

    title( ...
        layout_handle, ...
        figure_title, ...
        'FontSize', 20, ...
        'FontWeight', 'bold');

    axes_handles = gobjects(number_of_panels, 1);

    for panel = 1:number_of_panels

        axes_handles(panel) = nexttile(layout_handle);
        current_axis = axes_handles(panel);
        current_variable = panel_indices(panel);

        % Lower one-standard-deviation band.
        plot( ...
            current_axis, ...
            horizons, ...
            irfs_lower_plot(current_variable, :), ...
            'k--', ...
            'LineWidth', 1.2);

        hold(current_axis, 'on');

        % Upper one-standard-deviation band.
        plot( ...
            current_axis, ...
            horizons, ...
            irfs_upper_plot(current_variable, :), ...
            'k--', ...
            'LineWidth', 1.2);

        % Posterior mean impulse response.
        plot( ...
            current_axis, ...
            horizons, ...
            irfs_mean_plot(current_variable, :), ...
            'k-', ...
            'LineWidth', 1.8);

        yline( ...
            current_axis, ...
            0, ...
            'k:', ...
            'LineWidth', 1);

        title( ...
            current_axis, ...
            sprintf('%s. %s', ...
            panel_letters(panel), ...
            panel_titles{panel}), ...
            'FontSize', 18);

        xlabel( ...
            current_axis, ...
            'Months after Shock', ...
            'FontSize', 16);

        ylabel( ...
            current_axis, ...
            y_axis_labels{panel}, ...
            'FontSize', 16);

        if ~isempty(y_axis_limits{panel})
            ylim(current_axis, y_axis_limits{panel});
        end

        if ~isempty(y_axis_ticks{panel})
            yticks(current_axis, y_axis_ticks{panel});
        end

        xlim(current_axis, [0, 48]);
        xticks(current_axis, 0:3:48);

        current_axis.FontSize = 14;
        current_axis.Box = 'on';
        current_axis.LineWidth = 1;
    end

    linkaxes(axes_handles, 'x');
end
