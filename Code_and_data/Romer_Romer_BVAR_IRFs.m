%% Four Bayesian Cholesky SVAR specifications with model-specific tags
%
% Model suffixes:
%   _newm      = Romer-Romer new monetary policy measure, no commodity prices
%   _newm_com  = Romer-Romer new monetary policy measure, with commodity prices
%   _ff        = Federal funds rate, no commodity prices
%   _ff_com    = Federal funds rate, with commodity prices
%
% For every model, the code:
%   1. Estimates a Bayesian VAR using bvar_ and its default Jeffreys prior.
%   2. Retains posterior Cholesky IRF draws.
%   3. Normalises every draw separately so the policy variable rises by
%      one percentage point on impact.
%   4. Uses the mean across draws as the plotted point estimate.
%   5. Stores the pointwise standard deviation across draws at every horizon.
%   6. Plots mean +/- one pointwise standard deviation bands.
%
% Because the impact response is included as the first IRF column, setting
% opt.hor = 49 produces horizons 0 through 48 months.

clear;
clc;
close all;

% Fix the random-number seed so the Monte Carlo results are reproducible.
rng(4201);

%% Add the Empirical Macro Toolbox to the MATLAB path

addpath(fullfile(pwd, '..', 'BVAR_', 'bvartools'));

%% Import the Romer and Romer data

data_table = readtable( ...
    "RomerandRomerDataAppendix.xls", ...
    'Sheet', "DATA BY MONTH");

% Display imported variable names.
disp(data_table.Properties.VariableNames);

%% Extract the common data series

% Natural log of industrial production.
industrial_production_log = data_table.LNIPNSA;

% Natural log of producer prices.
producer_price_log = data_table.LNPPINSA;

% Natural log of world commodity prices.
commodity_prices_log = data_table.LNWCP;

% Cumulated Romer and Romer monetary policy shock/new measure.
new_measure = data_table.SUMSHCK;

% Federal funds rate, measured in percentage points.
fed_funds = data_table.FF;

%% Check whether SUMSHCK and SUMSHCKF are identical

same_shock_series = isequal( ...
    data_table.SUMSHCK, ...
    data_table.SUMSHCKF);

fprintf('Are SUMSHCK and SUMSHCKF identical? %d\n', ...
    same_shock_series);

%% Common Bayesian VAR settings

number_of_draws = 500;
irf_horizon_months = 48;

% bvar_ counts the impact response as its first horizon, so 49 columns are
% required to retain horizons 0, 1, ..., 48.
number_of_irf_columns = irf_horizon_months + 1;

desired_policy_impact = 1;


